-- Refresh step. Run after scripts/load_snowflake.py has filled STG_SOURCE_RECORDS.
-- Safe to run repeatedly. Derived tables are fully rebuilt on each run.

USE SCHEMA BLINDSPOT.CORE;

-- 1. Upsert the current record for each observation.
MERGE INTO SOURCE_RECORDS t
USING STG_SOURCE_RECORDS s
   ON t.RECORD_ID = s.RECORD_ID
WHEN MATCHED THEN UPDATE SET
    SOURCE_ID    = s.SOURCE_ID,
    RECORD_TYPE  = s.RECORD_TYPE,
    OBSERVED_AT  = s.OBSERVED_AT,
    SOURCE_URL   = s.SOURCE_URL,
    PAYLOAD      = PARSE_JSON(s.PAYLOAD_JSON),
    IS_SYNTHETIC = s.IS_SYNTHETIC,
    LOADED_AT    = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (RECORD_ID, SOURCE_ID, RECORD_TYPE, OBSERVED_AT, SOURCE_URL, PAYLOAD, IS_SYNTHETIC, LOADED_AT)
    VALUES (s.RECORD_ID, s.SOURCE_ID, s.RECORD_TYPE, s.OBSERVED_AT, s.SOURCE_URL, PARSE_JSON(s.PAYLOAD_JSON), s.IS_SYNTHETIC, CURRENT_TIMESTAMP());

-- 2. Keep history: add a row only when a payload is new for that record.
INSERT INTO SOURCE_RECORD_HISTORY (RECORD_ID, PAYLOAD_SHA256, PAYLOAD, LOADED_AT)
SELECT s.RECORD_ID, SHA2(s.PAYLOAD_JSON, 256), PARSE_JSON(s.PAYLOAD_JSON), CURRENT_TIMESTAMP()
FROM STG_SOURCE_RECORDS s
WHERE NOT EXISTS (
    SELECT 1 FROM SOURCE_RECORD_HISTORY h
    WHERE h.RECORD_ID = s.RECORD_ID AND h.PAYLOAD_SHA256 = SHA2(s.PAYLOAD_JSON, 256)
);

-- 3. Rebuild derived tables. Entities first, because the relationship views join to them.
INSERT OVERWRITE INTO ENTITIES
    (ENTITY_ID, ENTITY_KIND, NAME, NORMALIZED_NAME, REGISTRY_ID, STATE_CODE, SOURCE_RECORD_ID)
SELECT ENTITY_ID, ENTITY_KIND, NAME, NORMALIZED_NAME, REGISTRY_ID, STATE_CODE, SOURCE_RECORD_ID
FROM V_ENTITIES;

INSERT OVERWRITE INTO RELATIONSHIPS
    (RELATIONSHIP_ID, FROM_ENTITY_ID, TO_ENTITY_ID, RELATION_TYPE, STATUS, SOURCE_ID, SOURCE_RECORD_ID,
     SOURCE_URL, OBSERVED_AT, MATCH_METHOD, MATCH_RATIONALE)
SELECT RELATIONSHIP_ID, FROM_ENTITY_ID, TO_ENTITY_ID, RELATION_TYPE, STATUS, SOURCE_ID, SOURCE_RECORD_ID,
       SOURCE_URL, OBSERVED_AT, MATCH_METHOD, MATCH_RATIONALE
FROM V_RELATIONSHIPS;

INSERT OVERWRITE INTO REJECTED_MENTIONS (RECORD_ID, MENTION_NAME, REASON)
SELECT RECORD_ID, MENTION_NAME, REASON
FROM V_REJECTED_MENTIONS;
