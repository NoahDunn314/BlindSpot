-- Reproducibility and integrity checks. Every VIOLATIONS value should be 0.
-- scripts/load_snowflake.py runs this file and fails if any check is non-zero.

USE SCHEMA BLINDSPOT.CORE;

SELECT 'relationships_without_source_record' AS CHECK_NAME, COUNT(*) AS VIOLATIONS
FROM RELATIONSHIPS r
LEFT JOIN SOURCE_RECORDS s ON s.RECORD_ID = r.SOURCE_RECORD_ID
WHERE s.RECORD_ID IS NULL
UNION ALL
SELECT 'relationships_with_unknown_entity', COUNT(*)
FROM RELATIONSHIPS r
WHERE NOT EXISTS (SELECT 1 FROM ENTITIES e WHERE e.ENTITY_ID = r.FROM_ENTITY_ID)
   OR NOT EXISTS (SELECT 1 FROM ENTITIES e WHERE e.ENTITY_ID = r.TO_ENTITY_ID)
UNION ALL
SELECT 'duplicate_entity_ids', COUNT(*) - COUNT(DISTINCT ENTITY_ID)
FROM ENTITIES
UNION ALL
SELECT 'relationships_without_match_method', COUNT(*)
FROM RELATIONSHIPS
WHERE MATCH_METHOD IS NULL
UNION ALL
SELECT 'relationship_records_missing_from_graph', COUNT(*)
FROM SOURCE_RECORDS s
WHERE s.RECORD_TYPE = 'relationship'
  AND NOT EXISTS (SELECT 1 FROM RELATIONSHIPS r WHERE r.SOURCE_RECORD_ID = s.RECORD_ID)
  AND NOT EXISTS (SELECT 1 FROM REJECTED_MENTIONS m WHERE m.RECORD_ID = s.RECORD_ID);
